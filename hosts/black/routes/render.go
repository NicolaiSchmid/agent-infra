package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"net/url"
)

// Traefik's file provider reads YAML, and JSON is YAML: encoding/json does
// the quoting, so nothing a project pushes can break out of a string.
type dynamicConfig struct {
	HTTP httpConfig `json:"http"`
}

type httpConfig struct {
	Routers  map[string]router  `json:"routers"`
	Services map[string]service `json:"services,omitempty"`
}

type router struct {
	Rule        string    `json:"rule"`
	EntryPoints []string  `json:"entryPoints"`
	Service     string    `json:"service"`
	Priority    int       `json:"priority"`
	TLS         routerTLS `json:"tls"`
}

type routerTLS struct {
	CertResolver string `json:"certResolver"`
}

type service struct {
	LoadBalancer loadBalancer `json:"loadBalancer"`
}

type loadBalancer struct {
	Servers []server `json:"servers"`
	// False: the upstream sees its own hostname in Host (Vercel routes by
	// it); the original host stays in X-Forwarded-Host.
	PassHostHeader bool `json:"passHostHeader"`
}

type server struct {
	URL string `json:"url"`
}

// basePriority sits above Traefik's default (the rule's length) for any rule
// on these hosts; a longer pathPrefix adds to it, so the most specific
// prefix on a host wins.
const basePriority = 1000

// render turns a validated table into the project's Traefik dynamic file,
// or nil when the table is empty (Traefik rejects an empty http section).
// Names carry the project, so two projects' files never collide.
func render(project string, t *Table) []byte {
	if len(t.Routes) == 0 {
		return nil
	}
	cfg := dynamicConfig{HTTP: httpConfig{Routers: map[string]router{}, Services: map[string]service{}}}
	for i, r := range t.Routes {
		rule := fmt.Sprintf("Host(`%s`)", r.Host)
		if r.PathPrefix != "" {
			rule += fmt.Sprintf(" && PathPrefix(`%s`)", r.PathPrefix)
		}
		var svc string
		if r.Target.Convex != "" {
			// Defined by the Convex containers' labels (convex/compose.yaml).
			svc = fmt.Sprintf("%s-%s@docker", r.Target.Convex, r.Target.Origin)
		} else {
			u, _ := url.Parse(r.Target.URL)
			svc = fmt.Sprintf("routes-%s-s%d", project, i)
			cfg.HTTP.Services[svc] = service{LoadBalancer: loadBalancer{
				Servers: []server{{URL: "https://" + u.Hostname()}},
			}}
		}
		cfg.HTTP.Routers[fmt.Sprintf("routes-%s-r%d", project, i)] = router{
			Rule:        rule,
			EntryPoints: []string{"websecure"},
			Service:     svc,
			Priority:    basePriority + len(r.PathPrefix),
			TLS:         routerTLS{CertResolver: "letsencrypt"},
		}
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "# Generated by routes-api from the table project %s pushed. Do not edit:\n# the next push or restart overwrites it.\n", project)
	enc := json.NewEncoder(&b)
	enc.SetEscapeHTML(false)
	enc.SetIndent("", "  ")
	_ = enc.Encode(cfg)
	return b.Bytes()
}
