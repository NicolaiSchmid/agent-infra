// routes-api lets each project on black push its own Traefik routing table:
// PUT /v1/projects/{project}/routes with the project's API key replaces the
// table, after checking every route against the project's entry in the
// registry (hosts/black/routes.nix). Operations:
// runbooks/black-client-data-demo.md, section "Routes API".
package main

import (
	"flag"
	"fmt"
	"log/slog"
	"net/http"
	"os"
	"time"
)

func main() {
	var (
		config     = flag.String("config", "/config/registry.json", "registry generated by routes.nix")
		keysDir    = flag.String("keys", "/keys", "directory with <project>.sha256 key hashes")
		stateDir   = flag.String("state", "/state", "directory for the last accepted table per project")
		dynamicDir = flag.String("dynamic", "/dynamic", "Traefik's file provider directory")
		listen     = flag.String("listen", ":8080", "listen address")
		check      = flag.String("healthcheck", "", "GET this URL and exit 0 on success (container healthcheck)")
	)
	flag.Parse()
	log := slog.New(slog.NewTextHandler(os.Stderr, nil))

	if *check != "" {
		os.Exit(healthcheck(*check))
	}

	registry, err := loadRegistry(*config)
	if err != nil {
		fatal(log, "registry", err)
	}
	hashes, err := loadKeyHashes(*keysDir, registry)
	if err != nil {
		fatal(log, "keys", err)
	}
	s := &Server{
		registry: registry,
		hashes:   hashes,
		store:    &Store{stateDir: *stateDir, dynamicDir: *dynamicDir},
		log:      log,
	}
	if err := s.restore(); err != nil {
		fatal(log, "restore", err)
	}

	srv := &http.Server{
		Addr:              *listen,
		Handler:           s.routes(),
		ReadHeaderTimeout: 5 * time.Second,
		ReadTimeout:       15 * time.Second,
		WriteTimeout:      15 * time.Second,
		IdleTimeout:       60 * time.Second,
		MaxHeaderBytes:    16 << 10,
	}
	log.Info("listening", "addr", *listen, "projects", len(registry.Projects))
	fatal(log, "serve", srv.ListenAndServe())
}

func healthcheck(url string) int {
	c := http.Client{Timeout: 2 * time.Second}
	resp, err := c.Get(url)
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		return 1
	}
	resp.Body.Close()
	if resp.StatusCode >= 300 {
		return 1
	}
	return 0
}

func fatal(log *slog.Logger, what string, err error) {
	log.Error(what, "error", err)
	os.Exit(1)
}
